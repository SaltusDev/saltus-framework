#!/usr/bin/env node
/**
 * Generate the *.asset.php manifests that the enqueueing services read.
 *
 * These assets are plain browser files with no bundler, so there was no build
 * step to emit a manifest and dashboard.asset.php was maintained by hand next
 * to a second copy of the same dependencies and a different version inlined in
 * PHP. Both facts it records are derivable from the asset itself, so it is
 * derived here instead:
 *
 *   dependencies — the `wp.*` namespaces the script actually reads, mapped to
 *                  their script handles (`wp.element` -> `wp-element`).
 *   version      — a content hash over every file the manifest versions, so
 *                  editing the CSS busts the CSS URL too. A release number
 *                  would not: it only changes when someone remembers to bump
 *                  it, and it changes for every asset at once.
 *
 * Usage: node bin/generate-asset-manifests.mjs   (or `npm run assets:manifest`)
 *
 * Idempotent. Re-run it after editing any listed source; ObservabilityDashboardTest
 * fails if the committed manifest no longer matches its sources.
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))

/**
 * Assets that ship a manifest, listed explicitly: an enqueue has to opt in by
 * requiring the file, so discovering *.js and emitting manifests nothing reads
 * would be noise.
 */
const MANIFESTS = [
  {
    manifest: 'assets/Feature/Observability/dashboard.asset.php',
    sources: [
      'assets/Feature/Observability/dashboard.js',
      'assets/Feature/Observability/dashboard.css',
    ],
  },
]

/** Length of the emitted hash. Matches what @wordpress/dependency-extraction emits. */
const VERSION_LENGTH = 20

/**
 * Script handles for the `wp.*` namespaces a script reads.
 *
 * @param {string} source JavaScript source.
 * @return {string[]} Sorted handles.
 */
function dependencies(source) {
  const found = new Set()

  for (const [, namespace] of source.matchAll(/\bwp\.([A-Za-z][A-Za-z0-9]*)/g)) {
    found.add('wp-' + namespace.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase())
  }

  return [...found].sort()
}

/**
 * Render the manifest as PHP, aligned the way the rest of the codebase writes arrays.
 *
 * @param {string[]} deps   Script handles.
 * @param {string} version  Content hash.
 * @return {string} File contents.
 */
function render(deps, version) {
  const list = deps.length > 0 ? `[ ${deps.map((d) => `'${d}'`).join(', ')} ]` : '[]'

  return `<?php
/**
 * Generated by bin/generate-asset-manifests.mjs. Do not edit.
 *
 * Re-run \`npm run assets:manifest\` after editing the assets this versions.
 */
return [
\t'dependencies' => ${list},
\t'version'      => '${version}',
];
`
}

let written = 0

for (const entry of MANIFESTS) {
  const contents = entry.sources.map((source) => readFileSync(join(root, source)))
  const hash = createHash('sha256')

  for (const buffer of contents) {
    hash.update(buffer)
  }

  const deps = dependencies(
    entry.sources
      .map((source, i) => (source.endsWith('.js') ? contents[i].toString('utf8') : ''))
      .join('\n')
  )
  const output = render(deps, hash.digest('hex').slice(0, VERSION_LENGTH))
  const target = join(root, entry.manifest)

  let current = null
  try {
    current = readFileSync(target, 'utf8')
  } catch {
    current = null
  }

  if (current === output) {
    console.log(`${entry.manifest} already current`)
    continue
  }

  writeFileSync(target, output)
  written += 1
  console.log(`wrote ${entry.manifest}`)
}

console.log(`generate-asset-manifests: ${written} manifest(s) written.`)
