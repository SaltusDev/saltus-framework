		'years is now spelled differently.',
		'',
		'Validation also runs at registration, and the `/health` endpoint reports the verdict under',
		'`config` so a broken config is visible without CLI access.',
		'',
	];
}

/**
 * @param mixed $values
 * @return list<string>
 */
function to_string_list( $values ): array {
	if ( ! is_array( $values ) ) {
		return [];
	}

	return array_values( array_map( 'strval', $values ) );
}

/**
 * @param list<string> $values
 */
function inline_code_list( array $values ): string {
	if ( $values === [] ) {
		return '—';
	}

	return implode(
		', ',
		array_map(
			static function ( string $value ): string {
				return '`' . $value . '`';
			},
			$values
		)
	);
}

/**
 * Table cells cannot carry a raw pipe without splitting the column.
 */
function escape_cell( string $text ): string {
	return str_replace( '|', '\\|', $text );
}

function write_file_if_changed( string $path, string $content ): void {
	if ( file_exists( $path ) && file_get_contents( $path ) === $content ) {
		return;
	}

	if ( file_put_contents( $path, $content ) === false ) {
		throw new RuntimeException( 'Unable to write ' . $path );
	}
}
