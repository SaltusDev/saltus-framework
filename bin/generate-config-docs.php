/**
 * @param array<string, mixed> $meta
 * @return list<string>
 */
function meta_section( array $meta ): array {
	$lines = [
		'## `meta`',
		'',
		(string) $meta['description'],
		'',
		'### Box keys',
		'',
		'| Key | Notes |',
		'|---|---|',
	];

	/** @var array<string, array<string, mixed>> $structure */
	$structure = $meta['box_structure'];
	foreach ( $structure as $key => $spec ) {
		$notes = (string) ( $spec['description'] ?? '' );
		if ( isset( $spec['accepted'] ) && is_array( $spec['accepted'] ) ) {
			$notes .= ' Accepted: ' . inline_code_list( to_string_list( $spec['accepted'] ) ) . '.';
		}

		$lines[] = '| `' . $key . '` | ' . escape_cell( $notes ) . ' |';
	}

	$field_types = to_string_list( $meta['field_types'] );
	sort( $field_types );

	$lines[] = '';
	$lines[] = '### Field types';
	$lines[] = '';
	$lines[] = count( $field_types ) . ' types are recognized. The map passes through the';
	$lines[] = '`saltus/framework/meta/matched_fields` filter, so a site may add its own — which is why an';
	$lines[] = 'unrecognized type warns rather than erroring.';
	$lines[] = '';
	$lines[] = inline_code_list( $field_types );
	$lines[] = '';
	$lines[] = '---';
	$lines[] = '';

	return $lines;
}

