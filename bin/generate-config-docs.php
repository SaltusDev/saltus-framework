#!/usr/bin/env php
<?php
/**
 * Generate the model configuration reference from SchemaBuilder.
 *
 * Every constraint in the output is read back out of the schema the validator
 * itself consumes, so the document cannot describe rules the code does not
 * enforce. Edit the schema in src/Models/Config/SchemaBuilder.php, then run
 * `composer docs:config`.
 */

declare( strict_types=1 );

use Saltus\WP\Framework\Models\Config\SchemaBuilder;

$root = dirname( __DIR__ );
require_once $root . '/vendor/autoload.php';

// SchemaBuilder reaches CodestarMeta for the field-type map, which passes the map
// through a filter. Outside WordPress there is no filter runtime, so stand one in
// that returns the value untouched — the unfiltered map is exactly what we want to
// document as the framework's own baseline.
if ( ! function_exists( 'apply_filters' ) ) {
	function apply_filters( string $hook_name, $value, ...$args ) {
		return $value;
	}
}

if ( ! function_exists( '__' ) ) {
	function __( string $text, string $domain = 'default' ): string {
		return $text;
	}
}

$schema = ( new SchemaBuilder() )->build();

write_file_if_changed( $root . '/docs/api/config-reference.md', build_document( $schema ) );

echo 'Generated config reference for ' . count( $schema['known_top_level_keys'] ) . " top-level keys.\n";

/**
 * @param array<string, mixed> $schema
 */
function build_document( array $schema ): string {
	$lines = array_merge(
		heading_section(),
		type_section( $schema['type'] ),
		name_section( $schema['name'] ),
		active_section( $schema['active'] ),
		labels_section( $schema['labels'] ),
		meta_section( $schema['meta'] ),
		relationships_section( $schema['relationships'] ),
		features_section( $schema['features'] ),
		webmcp_section( $schema['webmcp'] ),
		ai_context_section( $schema['ai_context'] ),
		taxonomy_section( $schema['associations'], $schema['supported_post_types'] ),
		known_keys_section( $schema['known_top_level_keys'] ),
		validation_section()
	);

	return implode( "\n", $lines ) . "\n";
}

/**
 * @return list<string>
 */
function heading_section(): array {
	return [
		'# Model Configuration Reference',
		'',
		'<!-- This file is auto-generated by `composer docs:config`. Do not edit by hand. -->',
		'',
		'Every constraint below is read from `SchemaBuilder`, which the config validator',
		'also consumes. Where a rule lives in the consuming code — meta field types, relationship',
		'cardinalities, field permission operations — the schema reads it rather than keeping a copy,',
		'so this document cannot describe a rule the framework does not enforce.',
		'',
		'---',
		'',
	];
}

/**
 * @param array<string, mixed> $type
 * @return list<string>
 */
function type_section( array $type ): array {
	return [
		'## `type` (required)',
		'',
		(string) $type['description'],
		'',
		'Accepted values:',
		'',
		inline_code_list( to_string_list( $type['accepted'] ) ),
		'',
		'---',
		'',
	];
}

/**
 * @param array<string, mixed> $name
 * @return list<string>
 */
