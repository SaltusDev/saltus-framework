		'',
		'| Model type | Maximum length |',
		'|---|---|',
		'| Post type | ' . (int) $name['post_type_max'] . ' characters |',
		'| Taxonomy | ' . (int) $name['taxonomy_max'] . ' characters |',
		'',
		'---',
		'',
	];
}

