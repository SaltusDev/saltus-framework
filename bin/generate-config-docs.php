/**
 * @param array<string, mixed> $features
 * @return list<string>
 */
function features_section( array $features ): array {
	$lines = [
		'## `features`',
		'',
		(string) $features['description'],
		'',
		'| Section | Accepted keys | Notes |',
		'|---|---|---|',	];

	/** @var array<string, array<string, mixed>> $sections */
	$sections = $features['sections'];
	foreach ( $sections as $name => $spec ) {
		$keys  = to_string_list( $spec['keys'] ?? [] );
		$cell  = $keys === [] ? '—' : inline_code_list( $keys );
		$lines[] = '| `' . $name . '` | ' . $cell . ' | ' . escape_cell( (string) ( $spec['description'] ?? '' ) ) . ' |';
	}

	$lines[] = '';
	$lines[] = '---';
	$lines[] = '';

	return $lines;
}

